import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export function renderNativeContract(contract) {
  if (contract.version !== 'gim-native-contract-v1') throw Error('native contract must remain v1');
  const definitions = contract.types;
  const names = new Set(Object.keys(definitions));
  const resolveFields = (name, ancestors = new Set()) => {
    if (!names.has(name) || ancestors.has(name)) throw Error(`invalid contract type reference: ${name}`);
    const definition=definitions[name], next=new Set(ancestors);next.add(name);
    if(definition.$alias)return resolveFields(definition.$alias,next);
    return {...(definition.$base?resolveFields(definition.$base,next):{}),
      ...Object.fromEntries(Object.entries(definition).filter(([key])=>!key.startsWith('$')))};
  };
  const primitive = {string: ['string', 'String'], i64: ['number', 'i64'], u64: ['number', 'u64']};
  const tsType = type => primitive[type]?.[0] ?? type;
  const rustType = type => primitive[type]?.[1] ?? type;
  const header = '// Generated by contracts/generate-native.mjs. Edit contracts/native-v1.json.\n';
  const codes = Object.keys(contract.errors);
  const variant = code => code.toLowerCase().split('_').map(part => part[0].toUpperCase() + part.slice(1)).join('');
  let ts = header + `export const NATIVE_CONTRACT_VERSION = '${contract.version}' as const;\n`;
  ts += `export const NATIVE_ERROR_CODES = ${JSON.stringify(codes, null, 2)} as const;\nexport type NativeErrorCode = typeof NATIVE_ERROR_CODES[number];\n`;
  let rust = header + 'use serde::{Deserialize, Serialize};\n';
  rust += `pub const NATIVE_CONTRACT_VERSION: &str = "${contract.version}";\n`;
  rust += '#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\npub enum NativeErrorCode {\n';
  for (const code of codes) rust += `    #[serde(rename = "${code}")]\n    ${variant(code)},\n`;
  rust += '}\n';
  for (const name of names) {
    const definition=resolveFields(name);
    if(definitions[name].$alias) {
      ts+=`\nexport type ${name} = ${definitions[name].$alias};\n`;
      rust+=`\npub type ${name} = ${definitions[name].$alias};\n`;
      continue;
    }
    ts += `\nexport interface ${name} {\n`;
    rust += `\n#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct ${name} {\n`;
    for (const [key, field] of Object.entries(definition)) {
      if (!primitive[field.type] && !names.has(field.type) && field.type !== 'NativeErrorCode') throw Error(`unknown type: ${field.type}`);
      ts += `  ${key}${field.optional ? '?' : ''}: ${tsType(field.type)}${field.nullable ? ' | null' : ''};\n`;
      if (field.optional) rust += '    #[serde(default, skip_serializing_if = "Option::is_none")]\n';
      else if (field.nullable) rust += '    #[serde(deserialize_with = "required_nullable")]\n';
      const value = rustType(field.type);
      rust += `    pub ${key}: ${field.optional || field.nullable ? `Option<${value}>` : value},\n`;
    }
    ts += '}\n';rust += '}\n';
  }
  rust += '\nfn required_nullable<\'de, D, T>(deserializer: D) -> Result<Option<T>, D::Error>\nwhere D: serde::Deserializer<\'de>, T: Deserialize<\'de> { Option::<T>::deserialize(deserializer) }\n';
  return {ts, rust};
}

export function generateNativeContract({check = false, workspace = root} = {}) {
  const contract = JSON.parse(readFileSync(resolve(workspace, 'contracts/native-v1.json'), 'utf8'));
  const {ts, rust} = renderNativeContract(contract);
  for (const [file, value] of [
    ['packages/powerline-core/src/generated/nativeContracts.ts', ts],
    ['contracts/generated/native.rs', rust],
  ]) {
    const path = resolve(workspace, file);
    if (check) {
      if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== value) throw Error(`Generated contract is stale: ${file}`);
    } else {mkdirSync(dirname(path), {recursive: true});writeFileSync(path, value);}
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateNativeContract({check: process.argv.includes('--check')});
}
