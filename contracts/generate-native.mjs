import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('..',import.meta.url));
const variant=value=>value.toLowerCase().split(/[_-]/).map(part=>part[0].toUpperCase()+part.slice(1)).join('');
const snake=value=>value.replace(/([a-z0-9])([A-Z])/g,'$1_$2').toUpperCase();
const camel=value=>value.replace(/_([a-z])/g,(_,letter)=>letter.toUpperCase());
export function renderNativeContract(contract){
  if(contract.version!=='gim-native-contract-v1')throw Error('native contract must remain v1');
  const definitions=contract.types,enums=contract.enums??{},names=new Set(Object.keys(definitions));
  const primitive={string:['string','String'],i64:['number','i64'],u64:['number','u64'],u32:['number','u32'],usize:['number','usize'],u8:['number','u8'],f64:['number','f64'],bool:['boolean','bool'],json:['unknown','serde_json::Value']};
  function fields(name,parents=new Set()){
    if(!names.has(name)||parents.has(name))throw Error(`invalid contract type reference: ${name}`);
    const value=definitions[name],next=new Set(parents);next.add(name);if(value.$alias)return fields(value.$alias,next);
    return {...(value.$base?fields(value.$base,next):{}),...Object.fromEntries(Object.entries(value).filter(([key])=>!key.startsWith('$')))};
  }
  function type(value,language){
    if(typeof value==='object'){
      if(value.array)return language===0?`Array<${type(value.array,language)}>`:`Vec<${type(value.array,language)}>`;
      if(value.map)return language===0?`Record<string, ${type(value.map,language)}>`:`std::collections::HashMap<String, ${type(value.map,language)}>`;
      if(value.tuple)return language===0?`[${value.tuple.map(item=>type(item,language)).join(', ')}]`:`(${value.tuple.map(item=>type(item,language)).join(', ')})`;
      throw Error('unknown type descriptor');
    }
    if(primitive[value])return primitive[value][language];
    if(names.has(value)||value==='NativeErrorCode'||enums[value])return value;
    throw Error(`unknown type: ${value}`);
  }
  function comparable(value,seen=new Set()){
    if(typeof value==='object')return Object.values(value).flat().every(item=>comparable(item,seen));
    if(value==='f64')return false;if(!names.has(value)||seen.has(value))return true;
    const next=new Set(seen);next.add(value);return Object.values(fields(value)).every(field=>comparable(field.type,next));
  }
  const header='// Generated by contracts/generate-native.mjs. Edit contracts/native-v1.json.\n';
  let ts=header+`export const NATIVE_CONTRACT_VERSION = '${contract.version}' as const;\n`,rust=header+'use serde::{Deserialize, Serialize};\n';
  rust+=`pub const NATIVE_CONTRACT_VERSION: &str = "${contract.version}";\n`;
  const codes=Object.keys(contract.errors);ts+=`export const NATIVE_ERROR_CODES = ${JSON.stringify(codes,null,2)} as const;\nexport type NativeErrorCode = typeof NATIVE_ERROR_CODES[number];\n`;
  rust+='#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\npub enum NativeErrorCode {\n';
  for(const code of codes)rust+=`    #[serde(rename = "${code}")]\n    ${variant(code)},\n`;rust+='}\n';
  for(const [name,definition] of Object.entries(enums)){
    const values=definition.values;ts+=`\nexport const ${snake(name)}_VALUES = ${JSON.stringify(values)} as const;\nexport type ${name} = typeof ${snake(name)}_VALUES[number];\n`;
    if(definition.rust==='enum'){
      rust+=`\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\npub enum ${name} {\n`;
      for(const value of values)rust+=`    #[serde(rename = "${value}")]\n    ${variant(value)},\n`;rust+='}\n';
    }else{
      rust+=`\npub type ${name} = String;\npub const ${snake(name)}_VALUES: &[&str] = &[${values.map(value=>JSON.stringify(value)).join(', ')}];\n`;
      rust+=`fn deserialize_${name.toLowerCase()}<'de,D:serde::Deserializer<'de>>(deserializer:D)->Result<String,D::Error>{let value=String::deserialize(deserializer)?;if ${snake(name)}_VALUES.contains(&value.as_str()){Ok(value)}else{Err(serde::de::Error::custom("unsupported ${name}"))}}\n`;
    }
  }
  for(const [name,definition] of Object.entries(contract.constants??{})){
    ts+=`export const ${name} = ${JSON.stringify(definition.value)} as const;\n`;
    rust+=`pub const ${name}: ${definition.type==='string'?'&str':definition.type} = ${JSON.stringify(definition.value)};\n`;
  }
  for(const [group,definition] of Object.entries(contract.commands??{})){
    const label=snake(group),values=Object.fromEntries(definition.names.map(name=>[name,(definition.prefix??'')+name]));
    ts+=`export const ${label}_COMMANDS = ${JSON.stringify(values,null,2)} as const;\nexport type ${variant(label)}Command = typeof ${label}_COMMANDS[keyof typeof ${label}_COMMANDS];\n`;
    rust+=`pub const ${label}_COMMAND_NAMES: &[&str] = &[${definition.names.map(name=>JSON.stringify(name)).join(', ')}];\n`;
  }
  for(const name of names){
    const info=definitions[name];if(info.$alias){ts+=`\nexport type ${name} = ${info.$alias};\n`;rust+=`\npub type ${name} = ${info.$alias};\n`;continue;}
    const definition=fields(name),eq=comparable(name)?', Eq':'';
    ts+=`\nexport interface ${name}${info.$tsGeneric?`<${info.$tsGeneric}>`:''} {\n`;
    if(info.$tsIndex)ts+=`  [key: string]: ${info.$tsIndex};\n`;
    rust+=`\n#[derive(Debug, Clone, PartialEq${eq}${info.$deriveDefault?', Default':''}, Serialize, Deserialize)]\n#[serde(deny_unknown_fields${info.$renameAll?`, rename_all = "${info.$renameAll}"`:''})]\npub struct ${name} {\n`;
    for(const [key,field] of Object.entries(definition)){
      const wire=field.wireName??(info.$renameAll==='camelCase'?camel(key):key);
      ts+=`  ${wire}${field.optional?'?':''}: ${field.ts??type(field.type,0)}${field.nullable?' | null':''};\n`;
      const rustOptional=field.rustOptional??(field.optional||field.nullable);
      if(field.optional&&rustOptional&&field.skipNone!==false)rust+='    #[serde(default, skip_serializing_if = "Option::is_none")]\n';
      else if(field.default&&!field.skipFalse)rust+='    #[serde(default)]\n';
      else if(field.nullable&&!field.inputOptional)rust+='    #[serde(deserialize_with = "required_nullable")]\n';
      if(field.skipFalse)rust+='    #[serde(default, skip_serializing_if = "native_is_false")]\n';
      if(field.wireName)rust+=`    #[serde(rename = "${field.wireName}")]\n`;
      if(typeof field.type==='string'&&enums[field.type]?.rust!=='enum'&&enums[field.type])rust+=`    #[serde(deserialize_with = "deserialize_${field.type.toLowerCase()}")]\n`;
      const value=type(field.type,1);rust+=`    pub ${key}: ${rustOptional?`Option<${value}>`:value},\n`;
    }
    ts+='}\n';rust+='}\n';
    if(info.$borrowed){
      const view=info.$borrowed;
      rust+=`#[derive(Serialize)]\npub struct ${view.name}<'a> {\n`;
      for(const [key,field] of Object.entries(definition)){
        const value=type(field.type,1),optional=field.rustOptional??(field.optional||field.nullable);
        if(optional&&field.skipNone!==false)rust+='    #[serde(skip_serializing_if = "Option::is_none")]\n';
        const owned=view.owned?.includes(key),array=typeof field.type==='object'&&field.type.array;
        const borrowed=owned?value:array&&!optional?`&'a [${type(field.type.array,1)}]`:field.type==='string'&&!optional?"&'a str":`&'a ${value}`;
        rust+=`    pub ${key}: ${optional?`Option<${borrowed}>`:borrowed},\n`;
      }
      rust+='}\n';
    }
    if(info.$defaultValues){
      const values=Object.entries(info.$defaultValues).map(([key,value])=>`${key}: ${typeof value==='string'?JSON.stringify(value)+'.into()':JSON.stringify(value)}`).join(', ');
      rust+=`impl Default for ${name} {fn default()->Self {Self{${values}}}}\n`;
    }
  }
  rust+="\nfn required_nullable<'de,D,T>(deserializer:D)->Result<Option<T>,D::Error> where D:serde::Deserializer<'de>,T:Deserialize<'de>{Option::<T>::deserialize(deserializer)}\n";
  if(Object.values(definitions).some(definition=>Object.values(definition).some(field=>field&&typeof field==='object'&&field.skipFalse)))rust+='fn native_is_false(value:&bool)->bool{!*value}\n';
  rust+="#[cfg(test)]\npub fn roundtrip_native_model(name:&str,value:serde_json::Value)->Result<serde_json::Value,serde_json::Error>{match name {\n";
  for(const name of names)rust+=`    "${name}" => serde_json::from_value::<${name}>(value).and_then(serde_json::to_value),\n`;
  rust+='    _ => Err(<serde_json::Error as serde::de::Error>::custom("unknown native contract model")),\n}}\n';
  return {ts,rust};
}
export function generateNativeContract({check=false,workspace=root}={}){
  const contract=JSON.parse(readFileSync(resolve(workspace,'contracts/native-v1.json'),'utf8')),{ts,rust}=renderNativeContract(contract);
  for(const [file,value] of [['packages/powerline-core/src/generated/nativeContracts.ts',ts],['contracts/generated/native.rs',rust]]){
    const path=resolve(workspace,file);if(check){if(readFileSync(path,'utf8').replaceAll('\r\n','\n')!==value)throw Error(`Generated contract is stale: ${file}`);}else{mkdirSync(dirname(path),{recursive:true});writeFileSync(path,value);}
  }
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))generateNativeContract({check:process.argv.includes('--check')});
