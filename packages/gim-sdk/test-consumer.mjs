import {cpSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const root=dirname(fileURLToPath(import.meta.url)),repo=resolve(root,'../..');
const target=resolve(repo,'tmp/gim-sdk-consumer',`${Date.now()}-${process.pid}`);
const installed=join(target,'node_modules/@gim/gim-sdk');
mkdirSync(installed,{recursive:true});
cpSync(join(root,'dist'),join(installed,'dist'),{recursive:true});
cpSync(join(root,'package.json'),join(installed,'package.json'));
const manifest=JSON.parse(readFileSync(join(installed,'dist/build-manifest.json'),'utf8'));
const packageMetadata=JSON.parse(readFileSync(join(installed,'package.json'),'utf8'));
if(manifest.version!==packageMetadata.version||Object.keys(manifest.capabilities??{}).length!==6)
  throw Error('SDK build manifest is stale or lacks capability verification. Run the SDK build first.');
if(manifest.runtimeExternals.length)throw Error('SDK consumer needs external runtime dependencies');
writeFileSync(join(target,'consumer.mjs'),`
import assert from 'node:assert/strict';
import * as sdk from '@gim/gim-sdk';
import * as source from '@gim/gim-sdk/source';
import * as semantic from '@gim/gim-sdk/semantic';
import * as geometry from '@gim/gim-sdk/geometry';
import * as engineering from '@gim/gim-sdk/engineering';
import * as projection from '@gim/gim-sdk/projection';
import * as sourceAdapter from '@gim/gim-sdk/source-adapter';
assert.equal(globalThis.window,undefined);
const entrypoints={source,semantic,geometry,engineering,projection,sourceAdapter};
assert.deepEqual(Object.keys(sdk).sort(),Object.keys(entrypoints).sort());
for(const [name,api] of Object.entries(entrypoints))assert.deepEqual({...sdk[name]},{...api});
const text={'project.cbm':'OBJECTMODELPOINTER=unit.dev','unit.dev':'TYPE=GIS\\nSUBDEVICE0=part.dev','part.dev':'TYPE=CircuitBreaker'};
const graph=await source.extractEngineeringSourceGraph({paths:Object.keys(text),readText:async path=>text[path]});
const sources=source.collectEngineeringSources(graph,[],[]);
const snapshot=sourceAdapter.normalizeEngineeringSources('consumer',sources);
assert.equal(snapshot.entities.length,1);assert.equal(snapshot.memberships.length,2);
const rootRecord=source.engineeringSourceRecords(graph,[])[0];
const evidence=sourceAdapter.toObjectEvidence(rootRecord);
const neutral=semantic.normalizeEngineeringModel('neutral-consumer',[evidence]);
assert.equal(neutral.entities[0].category,snapshot.entities[0].category);
const physical=geometry.collectSourceGeometryOccurrences(graph);
assert.equal(physical.occurrences.length,1);
const addresses=graph.records.map(row=>({kind:'dev',sourceId:row.id,rootOccurrence:row.devOccurrence.rootSourceId,assemblyPath:row.devOccurrence.assemblyPath,devPath:row.source}));
const addressIndex=new geometry.RepresentationAddressIndex(addresses);
const binding=new engineering.EngineeringRepresentationIndex(snapshot,addresses);
assert.equal(addressIndex.sourcesForDev(physical.occurrences[0].sourceId).length,2);
assert.equal(binding.resolveDev(physical.occurrences[0].sourceId).status,'bound');
const view=projection.projectEngineeringNavigation(sources,snapshot);
assert.equal(view.inventory.rowsByEntity.size,1);assert.equal(view.composition.rowsByEntity.size,1);assert.equal(view.sourceRows.size,2);
assert.equal(projection.engineeringQuery(snapshot).tree(snapshot.entities[0].id).nodes.size,2);
const controller=new AbortController();controller.abort();
await assert.rejects(source.extractEngineeringSourceGraph({paths:Object.keys(text),readText:async path=>text[path]},{signal:controller.signal}),error=>error.name==='AbortError');
console.log(JSON.stringify({contract:'gim-sdk-consumer-v1',capabilities:5,entrypoints:7,entities:1,members:2,physicalRoots:1,views:3,windowAvailable:false}));
`);
const child=spawnSync(process.execPath,['consumer.mjs'],{cwd:target,encoding:'utf8',windowsHide:true,
 env:{...process.env,TEMP:target,TMP:target,TMPDIR:target}});
if(child.error)throw child.error;
process.stdout.write(child.stdout);process.stderr.write(child.stderr);
if(child.status!==0)process.exitCode=child.status??1;
