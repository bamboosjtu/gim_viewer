import {readFileSync,writeFileSync} from 'node:fs';

const data = name => JSON.parse(readFileSync(new URL(`./src/semantic/catalog/${name}.json`,import.meta.url),'utf8'));
function fingerprint(names, seeds) {
  const text=JSON.stringify(names.map(data));
  return seeds.map(([seed,multiplier,width])=>{
    let hash=seed;
    for(let i=0;i<text.length;i++)hash=Math.imul(hash^text.charCodeAt(i),multiplier);
    return (hash>>>0).toString(16).padStart(width,'0');
  }).join('');
}
const rules=fingerprint(['recognitionPolicy','compositionPolicy','standardCatalog'],[[2166136261,16777619,0]]);
const vocabulary=fingerprint(['sourceVocabulary','sourceCompatibilityPolicy','proxyCategories'],[[2166136261,16777619,8],[2246822519,3266489917,8]]);
const file=new URL('./src/semantic/policyFingerprints.ts',import.meta.url);
const content=`// Generated by policy-fingerprints.mjs from the recognition data.\nexport const POLICY_CONTENT = "${rules}";\nexport const VOCABULARY_CONTENT = "${vocabulary}";\n`;
if(process.argv.includes('--write'))writeFileSync(file,content.replaceAll('\n','\r\n'));
else if(readFileSync(file,'utf8').replaceAll('\r\n','\n')!==content)
  throw Error('Semantic policy fingerprints are stale. Run npm run sync:policy in packages/gim-sdk.');
