"""Prepare compact web metadata from the Blender build outputs.

The site layout (spawn, gate, main entrance, interior hints, landmarks) is read
from build/profile.json, generated by derive_profile.py. A source-bound profile
is required; no station-specific coordinate fallback is permitted.
"""
from __future__ import annotations

import json
import os
import shutil
from equipment_collision import bake_equipment

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BUILD = os.environ.get('GIM_BLENDER_BUILD', os.path.join(ROOT, 'build'))
WEB = os.environ.get('GIM_BLENDER_WEB', os.path.join(ROOT, 'web'))
ASSETS = os.path.join(WEB, 'assets')
RENDERS = os.environ.get('GIM_BLENDER_RENDERS', os.path.join(ROOT, 'renders'))
os.makedirs(ASSETS, exist_ok=True)

ifc = json.load(open(os.path.join(BUILD, 'ifc_scene.json'), encoding='utf-8'))
nav = json.load(open(os.path.join(BUILD, 'nav.json'), encoding='utf-8'))
gim = json.load(open(os.path.join(BUILD, 'gim_scene.json'), encoding='utf-8'))
for meta in (ifc, gim, nav):
    if meta.get('coordinateSystem') != 'source-z-up-metres-v2':
        raise RuntimeError('Regenerate IFC and GIM extracts in the source Z-up frame')

# IFC navigation and DEV collision are separate source tracks. Bake the placed
# DEV geometry before publishing so a visible device cannot lack its collider.
nav['equipment'] = bake_equipment(BUILD, ASSETS)
nav['navigationVersion'] = 3

profile_path = os.environ.get('GIM_BLENDER_PROFILE', os.path.join(BUILD, 'profile.json'))
if not os.path.exists(profile_path):
    raise RuntimeError('Site profile missing: run derive_profile.py before publishing')
profile = json.load(open(profile_path, encoding='utf-8'))
if profile.get('coordinateSystem') != 'source-z-up-metres-v2':
    raise RuntimeError('Site profile has an incompatible coordinate frame')
for required in ('slug', 'source', 'start'):
    if not profile.get(required):
        raise RuntimeError('Site profile is missing ' + required)
slug = profile['slug']
source = profile['source']
identity_path=os.path.join(BUILD,'identity.json')
identity=json.load(open(identity_path,encoding='utf-8')) if os.path.exists(identity_path) else {}
title = identity.get('displayName') or profile.get('title') or '变电站 · 第一人称漫游'

# Main entrance is a source-bound id from the generated or explicit profile.
main_entrance = None
main_id = (profile.get('mainEntrance') or {}).get('id')
for d in ifc['doors']:
    if main_id is not None and str(d['id']) == str(main_id):
        main_entrance = d
        break
if main_id is not None and main_entrance is None:
    raise RuntimeError('Configured main entrance is not present in this source IFC set')

doors = []
for d in ifc['doors']:
    rec = {
        'id': d['id'],
        'name': d['name'],
        'sourceId': d.get('sourceId'),
        'sourceFile': d.get('sourceFile'),
        'sourceType': d.get('sourceType'),
        'roleEvidence': d.get('roleEvidence'),
        'kind': d['kind'],
        'axis': d['axis'],
        'width': round(d['width'], 3),
        'height': round(d['height'], 3),
        'thickness': round(d['thickness'], 3),
        'bottom': round(d['bottom'], 3),
        'top': round(d['top'], 3),
        'bbox': [round(x, 3) for x in d['bbox']],
        'center': [round(x, 3) for x in d['center']],
        'material': d['material'],
        'category': d.get('category', ''),
        'main': main_entrance is not None and d['id'] == main_entrance['id'],
        'leaves': [
            {
                'name': l['name'],
                'kind': l.get('kind', 'swing'),
                'angle': round(float(l.get('angle', 0.0)), 5),
                'side': int(l.get('side', 1)),
                'width': round(float(l.get('width', 0.0)), 3),
                'height': round(float(l.get('height', 0.0)), 3),
                'hinge': [round(x, 3) for x in l.get('hinge', [0, 0, 0])],
                'moveZ': round(float(l.get('move_z', 0.0)), 3) if l.get('move_z') else 0.0,
            }
            for l in d['leaves']
        ],
    }
    doors.append(rec)

gate = profile.get('gate')
if gate:
    b = gate['bbox']
    gate.setdefault('center', [(b[0] + b[3]) / 2, (b[1] + b[4]) / 2, (b[2] + b[5]) / 2])
    gate.setdefault('id', 'GATE')
    gate.setdefault('name', '大门')
    gate['bbox'] = [round(x, 3) for x in gate['bbox']]
    gate['center'] = [round(x, 3) for x in gate['center']]

# Explicit empty arrays are valid source-derived results. Never populate a
# new project with the first demo's rooms, landmarks, or station coordinates.
interiors = profile.get('interiors') or []
landmarks = profile.get('landmarks') or []
buildings = profile.get('buildings') or []
start = profile['start']

main_c = main_entrance['center'] if main_entrance else None
gate_c = gate['center'] if gate else None
map_data = {
    'bounds': nav['bounds'],
    'gate': gate_c[:2] if gate_c else None,
    'mainEntrance': main_c[:2] if main_c else None,
}

scene = {
    'version': 4,
    'buildVersion': '2026.11.15-composite-nav-v6',
    'coordinateSystem': 'source-z-up-metres-v2',
    'title': title,
    'projectInfo': identity,
    'geometry': {'backend': gim.get('geometryBackend', 'legacy-python'),
        'lod': gim.get('geometryLod', 1),
        'status': 'partial' if gim['stats']['unsupported'] or gim.get('geometryFailures') else 'complete',
        'unsupportedEntities': gim['stats']['unsupported'],
        'failedVisibleOccurrences': len(gim.get('geometryFailures', []))},
    'source': source,
    'counts': {
        'ifcTriangles': ifc['counts']['triangles'],
        'gimTriangles': gim['stats']['tris'],
        'doors': len(doors),
        'gimPlacements': gim.get('dev_instances', gim.get('placements', 0)),
        'gimRoots': gim.get('placements', 0),
        'gimSolids': gim.get('solids', 0),
    },
    'start': start,
    'home': profile.get('home') or start,
    'doors': doors,
    'mainEntrance': main_entrance['id'] if main_entrance else None,
    'freeRoam': bool(profile.get('freeRoam')) or main_entrance is None,
    'gate': gate,
    'nav': nav,
    'interiors': interiors,
    'sourceInteriors': ifc.get('interiorAreas', []),
    'landmarks': landmarks,
    'map': map_data,
    'buildings': buildings,
}

with open(os.path.join(ASSETS, 'scene.json'), 'w', encoding='utf-8') as f:
    json.dump(scene, f, ensure_ascii=False, separators=(',', ':'))

# The web template always loads a stable world.glb; the source-derived slug is
# kept as a second copy for provenance.
glb_src = os.path.join(BUILD, f'{slug}.glb')
glb_world = os.path.join(ASSETS, 'world.glb')
if os.path.exists(glb_src):
    shutil.copy2(glb_src, glb_world)
    shutil.copy2(glb_src, os.path.join(ASSETS, f'{slug}.glb'))
else:
    raise RuntimeError(f'GLB not found: {glb_src}')

hero_src = os.path.join(RENDERS, 'overview.png')
if os.environ.get('GIM_BLENDER_SKIP_RENDERS') != '1' and os.path.exists(hero_src):
    shutil.copy2(hero_src, os.path.join(ASSETS, 'hero.png'))
else:
    for stale_name in ('hero.png', 'hero.jpg'):
        stale_path = os.path.join(ASSETS, stale_name)
        if os.path.exists(stale_path):
            os.remove(stale_path)
    # A no-render build must not claim another station's preview as its own.
    css_path=os.path.join(WEB,'css','style.css')
    if os.path.exists(css_path):
        with open(css_path,encoding='utf-8') as f: style=f.read()
        style=style.replace('url("../assets/hero.png")','linear-gradient(135deg,#173947,#07131c)')
        with open(css_path,'w',encoding='utf-8') as f:f.write(style)
if os.environ.get('GIM_BLENDER_SKIP_RENDERS') != '1' and os.path.exists(os.path.join(RENDERS, 'overview.jpg')):
    shutil.copy2(os.path.join(RENDERS, 'overview.jpg'), os.path.join(ASSETS, 'hero.jpg'))

print('wrote scene.json', os.path.getsize(os.path.join(ASSETS, 'scene.json')))
print('copied glb', os.path.getsize(glb_world))
