def norm(name):
    """名称归一：别名替换、去尺寸/括号/杂号前缀，拉丁转小写"""
    n = (name or '').strip().replace('（', '(').replace('）', ')')
    n = re.sub(r'_DEV$|_dev$', '', n)
    n = NOISE_PREFIX.sub('', n)
    n = n.lower()
    for a, b in ALIAS:
        n = n.replace(a, b)
    n = SIZE.sub('', n)
    n = MM.sub('', n)
    n = re.sub(r'\(.*?\)', '', n)
    n = re.sub(r'\s+', '', n)
    n = MODIFIER.sub('', n)
    n = TAIL_NUM.sub('', n)
    return n


def kind_of_empty(name, raw):
    """归一后为空：区分「尺寸占位名 / 备用占位 / 纯编号」"""
    r = (raw or '').strip()
    if PLACEHOLDER.match(r):
        return '占位名'
    if PURE_SIZE.match(r.replace('×', 'x').replace('*', 'x')) or SIZE.search(r):
        return '尺寸占位名'
    return '无法识别'


def template(name):
    """类型模板：再去掉全部数字与残留标点（用于「多少种类型」计数）"""
    n = norm(name)
    n = re.sub(r'\d+', '', n)
    n = n.replace('kv', '')
    n = re.sub(r'[_\-—.。、,，:：/]+', '', n)
    return n or ((name or '').strip() or '未命名')


def volt_of(name):
    m = VOLT.search(name or '')
    return m.group(1) + 'kV' if m else ''


def is_part(name):
    """是否「设备_部件」式的部件级挂接（判定见 split_part）"""
    return split_part(name)[1]


ATT_RE = re.compile(r'中性点成套|中性点装置|中性点设备')


def is_attachment(name):
    """是否变压器的附件（中性点成套装置）。

    业务口径：变压器 = 变压器本体 + 散热器 + 中性点成套装置。
    附件在 GIM 里可能被建成独立的 F4/DEV 节点，但**不单独计设备台数**，
    只作为所属变压器的组成记录。
    """
    return bool(ATT_RE.search(norm(name or '')))


def split_part(name):
    """拆出「父设备名 + 是否部件挂接」

    GIM 里常见把设备的子部件也挂成 F4 节点，名字是「避雷器模型01_土建接口」。
    这类节点按用户口径要**上卷到父设备**，不单独计为一种设备。
    """
    n = (name or '').strip()
    if '_' in n:
        head, tail = n.rsplit('_', 1)
        t = tail.strip()
        if t and CJK.search(t) and not re.fullmatch(r'[\d\s.\-]+', t):
            if any(w in t for w in PART_WORDS) or len(t) <= 6:
                return head.strip(), True
    return n, False


