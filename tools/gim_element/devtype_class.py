def classify(name, dev_type=''):
    """返回 (group, cat, rule_index)

    中文设备名是「定语+中心词」结构：取**最长命中关键词**，长度相同再取**最靠前**者
    （「主变间隔电流互感器」→ 电流互感器；「导线…主变及66kV配电装置」→ 导线）。
    """
    n = norm(name)
    t = (dev_type or '').lower()
    # 型钢/钢管杆件：PD420*12、L80*8、PL10*200、PIP50*4 这类「截面×壁厚」名，
    # 归一化后只剩两三个字母。实证（500-B1-4 构架 IFC）：PD420*12 对应
    # IFCCIRCLEHOLLOWPROFILEDEF 半径 210 / 壁厚 12 的圆空心截面，是构架杆件，
    # 不是管母线——必须归建构筑物，否则会被母线词条错吞。
    if re.match(r'^\s*(pd|pl|pip|l|c|h|i)\s*\d', name or '', re.I):
        return '建构筑物及辅助', '钢结构杆件', -4
    # 挂在绝缘子串上的防护金具：名称含「绝缘子」但本体是均压/屏蔽件，先归金具再谈绝缘子
    if re.search(r'均压|屏蔽环|屏蔽装置|间隔棒|防振|重锤', n):
        return '装置性材料', '金具', -5
    # 绝缘子按目录口径三分（2026-10-29 定稿）：支柱绝缘子（目录 11）、绝缘子串（目录附录）
    # 是甲供设备，按台 / 套供料安装；装置性材料里的「绝缘子」只收散装绝缘子。
    # 这一层放在 RULES 之前，是因为「单导V串绝缘子」的「绝缘子」在词尾，走「取最右中心词」
    # 会落到散装材料，而按目录它属于绝缘子串。
    if re.search(r'绝缘子|耐张串|悬垂串|跳线串|v串', n):
        if re.search(r'支柱|支持|柱式|针式|瓷横担|瓷套', n):
            return '装置性材料', '绝缘子', -5
        if re.search(r'串|耐张|悬垂|跳线', n):
            return '装置性材料', '绝缘子', -5
        # 其余（散装绝缘子、绝缘子支架…）不在这里截，交回 RULES 按中心词判，
        # 否则「绝缘子支架」会被从建构筑物里抢走
    # 穿墙套管按造价口径归装置性材料·M07 套管（目录 13 条目号仅作溯源）；
    # 「埋管-套管」这类土建预埋件同样落在 M07，故只认全词
    if '穿墙套管' in n:
        return '装置性材料', '套管', -5
    # 箱体一律设备（甲供）：照明箱/配电箱/检修箱/端子箱不会被「照明」「检修」等材料词吃掉
    if n.endswith('箱'):
        return '设备', ('二次设备' if '端子' in n else '动力辅助设施'), -3
    hits = []                       # (start, end, len, cat, grp, idx)
    for i, (cat, grp, _ref, pat) in enumerate(RULES):
        for m in re.finditer(pat, n):
            s0, e0 = m.start(), m.end()
            # 关键词后紧跟「+ / 及 / 区域 / 间隔 / 系统 / 配电装置」→ 是定语不是中心词
            tail = n[e0:]
            # 「+ / 、/ 及」后面接的是并列的另一串词，当前命中只是定语
            if re.match(r'[+、及]', tail):
                continue
            # 两字短词（主变/站变…）后面又跟「进线/出线/间隔/区域」→ 是间隔定语
            if e0 - s0 <= 2 and re.match(r'.{0,6}(区域|间隔|系统|配电装置|进线|出线|母线桥)', tail):
                continue
            hits.append((s0, e0, e0 - s0, cat, grp, i))
    if hits:
        # 1) 重叠的命中视为同一复合词，取最长（同长取最靠前）
        hits.sort(key=lambda h: (h[0], -h[2]))
        groups = []
        for h in hits:
            if groups and h[0] < groups[-1][1]:
                if h[2] > groups[-1][2]:
                    groups[-1] = h
            else:
                groups.append(h)
        # 2) 最靠右的一组即中心词
        s0, e0, _l, cat, grp, idx = groups[-1]
        if re.match(r'.{0,4}(间隔|系统)$', n[e0:]):
            return '未识别', '间隔/系统名（非设备）', idx
        return grp, cat, idx
    # 通用后缀兜底
    if re.search(r'柜$|屏$|机柜$', n):
        return '设备', '二次设备', -1
    if re.search(r'箱$', n):
        return '设备', '动力辅助设施', -1
    # 纯拉丁缩写名
    if n and not CJK.search(n) and len(n) <= 6:
        # 只认「短名缩写」：structural（含 ct）、upslope（含 ups）这类长串是误判源
        if re.fullmatch(r'[a-z0-9\-_]*ct[a-z0-9\-_]*', n):
            return '设备', '电流互感器', -2
        if re.fullmatch(r'[a-z0-9\-_]*pt[a-z0-9\-_]*', n):
            return '设备', '电压互感器', -2
    if re.search(r'(间隔|系统)$', n):
        return '未识别', '间隔/系统名（非设备）', -1
    if t in TYPE_MAP:
        return TYPE_MAP[t][0], TYPE_MAP[t][1], -1
    return '未识别', kind_of_empty(n, name), -1


def mat_sub(name, cat=None):
    """装置性材料二级判定 → (大类, 子类)。

    大类取自 MAT_L1 的 9 类；子类对金具（线夹/引流板/连接/接续/防护/母线金具）、
    绝缘子（支柱/串/散装）、接地材料、套管、槽盒、其他材料细分，其余大类返回 '本体'。
    非装置性材料返回 (None, None)。

    >>> mat_sub('耐张线夹带引流')
    ('金具', '线夹')
    >>> mat_sub('端子箱模型01')
    (None, None)
    """
    grp, c, _i = classify(name, '')
    if cat is not None:
        grp, c = '装置性材料', cat
    if grp != '装置性材料' or c not in MAT_L1:
        return None, None
    n = norm(name)
    for l1, sub, pat in MAT_SUB_RULES:
        if l1 == c and re.search(pat, n):
            return c, sub
    return c, '本体'


def mat_l1(name):
    """仅取大类（9 类之一），非材料返回 None。"""
    return mat_sub(name)[0]


